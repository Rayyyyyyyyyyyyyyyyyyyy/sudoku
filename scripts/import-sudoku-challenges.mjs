import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUZZLES } from '../src/data/puzzles.js';

// Download this exact file, then pass its local path as the first argument:
// https://raw.githubusercontent.com/grantm/sudoku-exchange-puzzle-bank/d8c8ebaee0c08c412cfba96af1923dfa61c83317/diabolical.txt
// node scripts/import-sudoku-challenges.mjs /tmp/sudoku-diabolical-d8c8eba.txt
// Only the challenge file is generated; the original five pools stay byte-for-byte intact.
const sourceCommit = 'd8c8ebaee0c08c412cfba96af1923dfa61c83317';
const sourceSha256 = '08553d0c1145ea4d7c13008040f47ea8205d21fe1eaf8f4ab17a1a6981928b35';
const minimumRating = 9.2;
const targetCount = 200;
const output = fileURLToPath(new URL('../src/data/sudokuChallengePuzzles.js', import.meta.url));

if (!process.argv[2] || process.argv.length !== 3) {
  throw new Error('Usage: node scripts/import-sudoku-challenges.mjs <fixed-source-diabolical.txt>');
}

const input = readFileSync(resolve(process.argv[2]));
if (createHash('sha256').update(input).digest('hex') !== sourceSha256) {
  throw new Error(`Source checksum mismatch; expected diabolical.txt from ${sourceCommit}`);
}

const records = input.toString('utf8').trim().split(/\r?\n/).map((line, index) => {
  const fields = line.trim().split(/\s+/);
  const [, digits, rawRating] = fields;
  const rating = Number(rawRating);
  if (fields.length !== 3 || !/^[0-9]{81}$/.test(digits) || !Number.isFinite(rating)) {
    throw new Error(`Invalid source record on line ${index + 1}`);
  }
  return [digits, rating];
});

// Keep validation independent from sudoku.js so this importer also works before
// its output exists. Stop at two solutions: both zero and multiple are rejected.
function solutionCount(digits) {
  const grid = Array.from(digits, Number);
  const rows = Array(9).fill(0);
  const columns = Array(9).fill(0);
  const boxes = Array(9).fill(0);
  const boxOf = (row, col) => Math.floor(row / 3) * 3 + Math.floor(col / 3);
  for (let i = 0; i < 81; i++) {
    if (!grid[i]) continue;
    const row = Math.floor(i / 9), col = i % 9, box = boxOf(row, col);
    const bit = 1 << grid[i];
    if ((rows[row] | columns[col] | boxes[box]) & bit) return 0;
    rows[row] |= bit;
    columns[col] |= bit;
    boxes[box] |= bit;
  }
  function search(limit) {
    let cell = -1, options = 0, fewest = 10;
    for (let i = 0; i < 81; i++) {
      if (grid[i]) continue;
      const row = Math.floor(i / 9), col = i % 9;
      const mask = 0x3fe & ~(rows[row] | columns[col] | boxes[boxOf(row, col)]);
      if (!mask) return 0;
      let count = 0;
      for (let bits = mask; bits; bits &= bits - 1) count++;
      if (count < fewest) {
        cell = i; options = mask; fewest = count;
        if (count === 1) break;
      }
    }
    if (cell < 0) return 1;
    const row = Math.floor(cell / 9), col = cell % 9, box = boxOf(row, col);
    let total = 0;
    for (let bits = options; bits && total < limit; bits &= bits - 1) {
      const bit = bits & -bits;
      grid[cell] = Math.log2(bit);
      rows[row] |= bit; columns[col] |= bit; boxes[box] |= bit;
      total += search(limit - total);
      rows[row] ^= bit; columns[col] ^= bit; boxes[box] ^= bit;
      grid[cell] = 0;
    }
    return total;
  }
  return search(2);
}

const known = new Set(PUZZLES.flat().map(([digits]) => digits));
const eligible = records.filter(([, rating]) => rating >= minimumRating);
const selected = eligible.slice(0, targetCount);
if (!selected.length) throw new Error('No challenge puzzles meet the minimum rating');
for (const [digits] of selected) {
  if (known.has(digits)) throw new Error(`Duplicate puzzle: ${digits}`);
  if (solutionCount(digits) !== 1) throw new Error(`Puzzle must have exactly one solution: ${digits}`);
  known.add(digits);
}

const metadata = {
  commit: sourceCommit,
  file: 'diabolical.txt',
  sha256: sourceSha256,
  minimumRating,
  sourceRecordCount: records.length,
  eligibleCount: eligible.length
};
const header = `// Generated by scripts/import-sudoku-challenges.mjs; do not edit by hand.\n// Source: https://github.com/grantm/sudoku-exchange-puzzle-bank/blob/${sourceCommit}/diabolical.txt\n// Public domain. Each entry preserves [81-digit puzzle, Sukaku Explainer rating].\n`;
writeFileSync(output, `${header}export const SUDOKU_CHALLENGE_SOURCE = ${JSON.stringify(metadata, null, 2)};\n\nexport const SUDOKU_CHALLENGE_PUZZLES = ${JSON.stringify(selected, null, 2)};\n`);
console.log(`Wrote ${selected.length} unique-solution puzzles (SE ${Math.min(...selected.map(([, rating]) => rating))}–${Math.max(...selected.map(([, rating]) => rating))}); source supplies ${eligible.length}/${targetCount} requested puzzles.`);
